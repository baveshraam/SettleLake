"""SettleLake financial operations dashboard (Streamlit). Reads Gold/meta data via DuckDB views."""

from __future__ import annotations

import json

import streamlit as st

from settlelake.analytics.views import open_analytics
from settlelake.config import ALL_CLASSES, CURRENCIES, get_paths

st.set_page_config(page_title="SettleLake", page_icon="💱", layout="wide")
paths = get_paths()


def q(sql: str, params: list | None = None):
    con = open_analytics(paths)
    try:
        return con.execute(sql, params or []).df()
    finally:
        con.close()


def banner(title: str) -> None:
    st.title(title)
    st.warning("SYNTHETIC DATA: generated by SettleLake's simulator. No real payments, "
               "customers or banking partners.", icon="🧪")  # fmt: skip


def money(minor: int, currency: str) -> str:
    exp = CURRENCIES[currency]
    return f"{minor / 10**exp:,.{exp}f} {currency}" if exp else f"{minor:,} {currency}"


if not (paths.gold / "reconciliation.parquet").exists():
    banner("SettleLake")
    st.error("No Gold data found. Run `settlelake generate` then `settlelake run`.")
    st.stop()

page = st.sidebar.radio("Section", ["Overview", "Payment Intelligence", "Reconciliation Center",
                                    "Pipeline Observability"])  # fmt: skip
st.sidebar.caption(f"Data directory: {paths.home}")

if page == "Overview":
    banner("SettleLake: Cross-Border Payments Data Platform")
    s = q("""SELECT (SELECT count(*) FROM fact_payments) payments,
                    count(*) n_keys, count(*) FILTER (WHERE classification='MATCHED') matched,
                    count(*) FILTER (WHERE classification<>'MATCHED') exceptions
             FROM reconciliation""").iloc[0]
    quarantined = q("SELECT count(*) n FROM (SELECT 1 FROM read_parquet(?) UNION ALL "
                    "SELECT 1 FROM read_parquet(?))",
                    [(paths.silver / "quarantine.parquet").as_posix(),
                     (paths.silver / "rejected.parquet").as_posix()]).iloc[0, 0]  # fmt: skip
    runs = q(
        "SELECT run_id, kind, status, started_at, duration_s FROM meta.runs "
        "ORDER BY started_at DESC LIMIT 1"
    )
    c = st.columns(5)
    c[0].metric("Total payments", f"{int(s.payments):,}")
    c[1].metric(
        "Reconciliation match rate", f"{100 * s.matched / s.n_keys:.2f}%" if s.n_keys else "n/a"
    )
    c[2].metric("Unresolved exceptions", f"{int(s.exceptions):,}")
    c[3].metric("Quarantined / rejected records", f"{int(quarantined):,}")
    c[4].metric("Latest run", runs.iloc[0].status if len(runs) else "none")
    st.subheader("Exceptions by classification")
    st.bar_chart(q("SELECT classification, count(*) records FROM reconciliation "
                   "WHERE classification<>'MATCHED' GROUP BY 1 ORDER BY 2 DESC"),
                 x="classification", y="records")  # fmt: skip
    st.subheader("Latest pipeline run")
    st.dataframe(runs, hide_index=True, use_container_width=True)

elif page == "Payment Intelligence":
    banner("Payment Intelligence")
    st.caption("Amounts are shown per currency; different currencies are never summed together.")
    cur_df = q("SELECT * FROM v_volume_by_currency")
    cur = st.selectbox("Currency for amount charts", cur_df.currency.tolist())
    left, right = st.columns(2)
    with left:
        st.subheader("Payments per day")
        st.line_chart(q("SELECT payment_date, count(*) payments FROM fact_payments GROUP BY 1 ORDER BY 1"),
                      x="payment_date", y="payments")  # fmt: skip
        st.subheader(f"Daily volume in {cur} (major units)")
        d = q("SELECT payment_date, total_minor FROM v_daily_volume WHERE currency = ?", [cur])
        d["volume"] = (
            d.total_minor / 10 ** CURRENCIES[cur]
        )  # display only; stored values stay integers
        st.bar_chart(d, x="payment_date", y="volume")
    with right:
        st.subheader("Currency distribution (payment count)")
        st.bar_chart(cur_df, x="currency", y="payments")
        st.subheader("Corridor distribution")
        st.bar_chart(
            q("SELECT corridor, payments FROM v_corridor_analytics"), x="corridor", y="payments"
        )
    st.subheader("Provider performance")
    st.dataframe(
        q("SELECT * FROM v_provider_performance"), hide_index=True, use_container_width=True
    )
    st.subheader("Outstanding settlements (no funds.settled yet)")
    st.dataframe(q("SELECT * FROM v_outstanding_settlements LIMIT 500"), hide_index=True,
                 use_container_width=True)  # fmt: skip

elif page == "Reconciliation Center":
    banner("Reconciliation Center")
    prov = q("SELECT DISTINCT provider FROM reconciliation ORDER BY 1").provider.tolist()
    corr = q(
        "SELECT DISTINCT corridor FROM reconciliation WHERE corridor IS NOT NULL ORDER BY 1"
    ).corridor.tolist()
    f1, f2, f3, f4 = st.columns([1, 1, 1, 2])
    sel_p = f1.multiselect("Provider", prov)
    sel_c = f2.multiselect("Corridor", corr)
    sel_k = f3.multiselect("Classification", [c for c in ALL_CLASSES if c != "MATCHED"])
    text = f4.text_input("Search (match key, payment id, explanation)")
    where, params = ["classification <> 'MATCHED'"], []
    for col, sel in (("provider", sel_p), ("corridor", sel_c), ("classification", sel_k)):
        if sel:
            where.append(f"{col} IN ({', '.join('?' * len(sel))})")
            params += sel
    if text:
        where.append("(match_key ILIKE ? OR payment_id ILIKE ? OR explanation ILIKE ?)")
        params += [f"%{text}%"] * 3
    df = q("SELECT reconciliation_id, classification, reasons, provider, corridor, payment_id, "
           "match_key, internal_amount_minor, internal_currency, partner_amount_minor, "
           "partner_currency, partner_status, settlement_lag_seconds, ingestion_lag_seconds, "
           f"explanation FROM reconciliation WHERE {' AND '.join(where)} ORDER BY match_key LIMIT 2000",
           params)  # fmt: skip
    st.caption(f"{len(df)} exception(s) shown (max 2000)")
    event = st.dataframe(df, hide_index=True, use_container_width=True, on_select="rerun",
                         selection_mode="single-row")  # fmt: skip
    if event.selection.rows:
        row = df.iloc[event.selection.rows[0]]
        st.subheader(f"Decision detail: {row.match_key}")
        a, b = st.columns(2)
        i_amt = (
            None
            if row.internal_amount_minor != row.internal_amount_minor
            else int(row.internal_amount_minor)
        )
        p_amt = (
            None
            if row.partner_amount_minor != row.partner_amount_minor
            else int(row.partner_amount_minor)
        )
        a.markdown("**Internal settlement**")
        a.write(money(i_amt, row.internal_currency) if i_amt is not None else "none / ambiguous")
        b.markdown("**Partner statement**")
        b.write(f"{money(p_amt, row.partner_currency)} ({row.partner_status})" if p_amt is not None
                else "none / ambiguous")  # fmt: skip
        st.write({"classification": row.classification, "all reasons": list(row.reasons),
                  "settlement lag (s)": row.settlement_lag_seconds,
                  "ingestion lag (s)": row.ingestion_lag_seconds})  # fmt: skip
        st.info(row.explanation)

else:
    banner("Pipeline Observability")
    st.subheader("Processing and replay runs")
    st.dataframe(q("SELECT run_id, kind, parent_run_id, status, replay_result, started_at, duration_s, "
                   "error FROM meta.runs ORDER BY started_at DESC"), hide_index=True,
                 use_container_width=True)  # fmt: skip
    st.subheader("Stage execution times")
    stats = q("SELECT * FROM v_pipeline_stats ORDER BY started_at DESC LIMIT 100")
    st.dataframe(stats, hide_index=True, use_container_width=True)
    latest = q(
        "SELECT run_id FROM meta.runs WHERE kind='pipeline' AND status='COMPLETED' "
        "ORDER BY started_at DESC LIMIT 1"
    )
    if len(latest):
        rid = latest.iloc[0, 0]
        st.bar_chart(stats[stats.run_id == rid], x="stage", y="stage_seconds")
        st.subheader(f"Data quality results ({rid})")
        st.dataframe(q("SELECT check_name, layer, severity, status, evaluated_count, failed_count, "
                       "round(duration_ms, 2) duration_ms, explanation FROM meta.quality_results "
                       "WHERE run_id = ? ORDER BY status DESC, check_name", [rid]),
                     hide_index=True, use_container_width=True)  # fmt: skip
    st.subheader("Data quality trend")
    st.dataframe(q("SELECT * FROM v_dq_trend"), hide_index=True, use_container_width=True)
    st.subheader("Benchmark results")
    bf = paths.reports / "benchmark.json"
    if bf.exists():
        st.json(json.loads(bf.read_text(encoding="utf-8")), expanded=False)
    else:
        st.info("No benchmark recorded. Run `settlelake benchmark`.")
